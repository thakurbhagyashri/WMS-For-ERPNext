const resources = Object.fromEntries(
  Object.entries(rawTranslations).map(([lang, translation]) => [lang, { translation }])
);

const LANGUAGE_KEY = 'app_language';

const defaultLocale = Localization.getLocales()[0]?.languageCode || 'en';

i18n
  .use(initReactI18next)
  .init({
    compatibilityJSON: 'v4',
    resources,
    lng: defaultLocale,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
  });

const initI18n = async () => {
  const savedLanguage = await storage.getItem(LANGUAGE_KEY);
  if (savedLanguage && savedLanguage !== defaultLocale) {
    i18n.changeLanguage(savedLanguage);
  }
};

initI18n();

export const changeLanguage = async (lng: string) => {
  await storage.setItem(LANGUAGE_KEY, lng);
  await i18n.changeLanguage(lng);
};

export default i18n;
